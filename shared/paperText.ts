export const PAPERS: Record<PaperName, Part[]> = { rules: RULES, data: DATA, contact: CONTACT };

/** The number a clause has at a position: "4.1" for the first clause of the fourth part. */
export function numberAt(part: number, clause: number): string {
  return `${part + 1}.${clause + 1}`;
}

/** Where a clause with this key is, and what it is numbered now. */
export function placeOf(key: string): { paper: PaperName; number: string } | null {
  for (const paper of Object.keys(PAPERS) as PaperName[]) {
    const parts = PAPERS[paper];
    for (let p = 0; p < parts.length; p++) {
      const at = parts[p]!.clauses.findIndex((clause) => clause.key === key);
      if (at >= 0) return { paper, number: numberAt(p, at) };
    }
  }
  return null;
}

/** A rule a decision can cite: what it is called and what it is numbered now. */
export interface Breakable {
  key: string;
  number: string;
  short: string;
}

/** Every clause a model or a comment can be taken down under, in the order they stand. */
export const BREAKABLE: Breakable[] = RULES.flatMap((part, p) =>
  part.clauses.flatMap((clause, c) =>
    clause.key && clause.short ? [{ key: clause.key, number: numberAt(p, c), short: clause.short }] : [],
  ),
);

export function isBreakable(key: unknown): key is string {
  return typeof key === 'string' && BREAKABLE.some((one) => one.key === key);
}

/**
 * The sentence a notice carries about the rule it cites.
 *
 * The number written in is the one in force today. If the rules are renumbered later,
 * the notice keeps saying what was broken in words, and its link follows the key.
 */
export function citing(key: string): string {
  const rule = BREAKABLE.find((one) => one.key === key);
  if (!rule) return '';
  const what = rule.short.charAt(0).toLowerCase() + rule.short.slice(1);
  return `Нарушен пункт ${rule.number} правил: ${what}.`;
}
