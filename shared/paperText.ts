/**
 * The words of the rules, the data notice and the contacts, as numbered clauses.
 *
 * <h2>Why numbered</h2>
 *
 * The first version read as a page of friendly advice: headings, paragraphs, a list in
 * the middle. Nobody could point at a sentence of it. A rule with a number can be
 * linked to (`/rules#4.1`), quoted back in an argument, and — the reason this is data
 * and not markup — named in the decision that enforces it. Article 17(3)(e) of
 * Regulation (EU) 2022/2065 asks a statement of reasons for "a reference to the
 * contractual ground relied on"; a clause number is exactly that.
 *
 * <h2>Why data in `shared/`</h2>
 *
 * Because the page and the Worker have to agree on the numbers. The page draws them;
 * the Worker writes "пункт 4.1" into the notice an author gets when their model is
 * taken down. Kept in two places they would drift on the first clause anybody added.
 *
 * Numbers are never written down. They are positions, counted when asked for, so a
 * clause added in the middle renumbers everything after it and nothing can disagree.
 * What a decision stores is the clause's `key`, which does not move; the number is the
 * one in force when the notice was written, and the text of that notice says so.
 *
 * <h2>The little markup in the text</h2>
 *
 * `[words](paper)` and `[words](paper#key)` are links to a page or to a clause on it.
 * `{n:key}` is the number of a clause. `{name}`, `{closedIn}` and `{email}` are filled
 * in by the page from what it knows at the time. Anything else is plain text.
 *
 * Every limit named here is read from the constant that enforces it, so the rules
 * cannot promise twenty-five megabytes while the Worker refuses at twenty.
 */

export type PaperName = 'rules' | 'data' | 'contact';

export interface Clause {
  /** A stable name, for links and for decisions that cite the clause. Unique across all three papers. */
  key?: string;
  /**
   * What the clause forbids, in a few words, on a clause a person can be told they broke.
   * Only clauses with one are offered when a model or a comment is taken down.
   */
  short?: string;
  text: string;
}

export interface Part {
  title: string;
  clauses: Clause[];
}

const MB = 1024 * 1024;

/** One, few, many: the three forms a Russian noun takes after a number. */
export function plural(n: number, one: string, few: string, many: string): string {
  const tens = n % 100;
  const units = n % 10;
  if (tens >= 11 && tens <= 14) return `${n} ${many}`;
  if (units === 1) return `${n} ${one}`;
  if (units >= 2 && units <= 4) return `${n} ${few}`;
  return `${n} ${many}`;
}

